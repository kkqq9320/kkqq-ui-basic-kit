/* 레이아웃을 흔드는 측정을 **스크롤 위치를 파괴하지 않고** 수행합니다.
 *
 * ⚠️ **문서가 짧아지면 브라우저는 그 자리에서 스크롤 위치를 깎고, 문서가 다시 길어져도
 * 되돌려 주지 않습니다.** 실측(실제 크롬, 창 1278x1214, 레이아웃 탭, `main` `6c8d830`):
 *
 *   스크롤 87  → 옛 규칙 주입: 문서 1357 → **1214**(= 창 높이), 최대 스크롤 **0**, scrollY **0**
 *              → 옛 규칙 제거: 문서 1357 복구, 최대 스크롤 143, scrollY **여전히 0**
 *
 * `main.tsx`의 조작판이 400ms마다 옛 규칙을 얹었다 걷는 탓에, 레이아웃 페이지에서
 * 스크롤한 지 0.4초 안에 화면이 맨 위로 튀었습니다(오너 리포트 2026-08-12 (b):
 * "아래로 스크롤하자마자 바로 위로 깜빡이며 올라온다"). 실제 코드로 끝에서 끝까지
 * 재현했습니다 — `t=0` scrollY 87, `t=250ms` 0, 이후 계속 0.
 *
 * **같은 동기 블록 안에서 저장·복원하는 것으로 충분합니다.** 블록 안에서는 페인트가
 * 일어나지 않으므로 사용자에게는 아무 일도 안 일어난 것이 됩니다(실측 87 → 0 → **87**).
 *
 * ⚠️ **조건 없이 되돌리면 안 됩니다.** 400ms마다 무조건 `scrollTo`를 부르면 진행 중인
 * 부드러운 스크롤·관성 스크롤을 그때마다 끊습니다. 실제로 깎였을 때만 되돌립니다.
 *
 * `finally`인 이유: `run()`이 던져도 스크롤은 되돌아와야 합니다. 던진 채로 두면
 * 조작판 하나가 고장 났을 때 **페이지가 스크롤되지 않는 것처럼** 보입니다.
 *
 * 여기 있는 이유: `demo/`는 `package.json`의 `files`에 없어 **소비자에게 배포되지
 * 않습니다.** 이건 데모 진단 도구의 결함이지 킷의 결함이 아닙니다.
 */
export function preservingScroll<T>(run: () => T): T {
  const x = window.scrollX;
  const y = window.scrollY;
  try {
    return run();
  } finally {
    if (window.scrollX !== x || window.scrollY !== y) window.scrollTo(x, y);
  }
}
